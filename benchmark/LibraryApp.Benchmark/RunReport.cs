using System.Globalization;
using System.Text;

namespace LibraryApp.Benchmark;

/// <summary>
/// The Markdown report of one run: the result per endpoint, the manifest (code, machine, database, settings) and every
/// measured time, so the numbers can be checked and compared later. File name: <c>yyyy-MM-dd[_tag]_commit[-dirty].md</c>
/// (Asia/Yerevan date); a second run of the same day and commit gets <c>_2</c>, <c>_3</c>, ...
/// </summary>
public sealed record RunReport(
    BenchmarkArguments Arguments,
    DateTimeOffset StartedAt,
    DateTimeOffset FinishedAt,
    MachineInfo Machine,
    RepositoryInfo Repository,
    DatabaseSnapshot? Database,
    IReadOnlyList<EndpointResult> Results)
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    public string Write(string directory)
    {
        Directory.CreateDirectory(directory);

        var date = TimeZoneInfo.ConvertTime(StartedAt, BenchmarkRun.Yerevan).ToString("yyyy-MM-dd", Invariant);
        var name = date
                   + (Repository.Tag is { } tag ? $"_{tag}" : "")
                   + $"_{Repository.ShortCommit}"
                   + (Repository.Dirty ? "-dirty" : "");

        var path = Path.Combine(directory, name + ".md");
        for (var n = 2; File.Exists(path); n++)
            path = Path.Combine(directory, $"{name}_{n}.md");

        File.WriteAllText(path, Render(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        return path;
    }

    private string Render()
    {
        var passed = Results.Count(r => r.Passed);
        var text = new StringBuilder();
        void Line(string value = "") => text.Append(value).Append('\n');
        string Ms(double value) => value.ToString("F1", Invariant);
        string N(int value) => value.ToString("N0", Invariant);
        string Time(DateTimeOffset value) =>
            $"{value.UtcDateTime.ToString("yyyy-MM-dd HH:mm:ss", Invariant)} UTC " +
            $"({TimeZoneInfo.ConvertTime(value, BenchmarkRun.Yerevan).ToString("yyyy-MM-dd HH:mm:ss", Invariant)} Asia/Yerevan)";

        Line($"# API benchmark — {Repository.Tag ?? Repository.ShortCommit} — {(passed == Results.Count ? "PASS" : "FAIL")}");
        Line();
        Line("NFR-01: \"Typical API calls respond in under 500 ms; reports in under 2 s on 10,000 loans.\" " +
             "Generated by `benchmark/LibraryApp.Benchmark` (README, \"Performance benchmark\"); do not edit by hand.");
        Line();
        Line($"**Result:** {passed} of {Results.Count} endpoints within their limit. An endpoint passes when every call succeeded " +
             "and its 95th percentile is within the limit; the maximum is shown next to it.");
        Line();

        Line("## Results");
        Line();
        Line("| Endpoint | Role | Limit, ms | Calls | Min | p50 | p95 | Max | Mean | First call | Errors | Result |");
        Line("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|");
        foreach (var r in Results)
            Line($"| {r.Endpoint.Name} `GET /{r.Endpoint.Path}` | {r.Endpoint.Caller} | {r.Endpoint.LimitMs} | {r.Samples.Length} | " +
                 $"{Ms(r.Min)} | {Ms(r.P50)} | {Ms(r.P95)} | {Ms(r.Max)} | {Ms(r.Mean)} | {(r.FirstCall is { } first ? Ms(first) : "—")} | " +
                 $"{(r.Errors == 0 ? "0" : $"{r.Errors} ({r.FirstError})")} | {(r.Passed ? "pass" : "**FAIL**")} |");
        Line();
        Line("Times in milliseconds. \"First call\" is the first warm-up call, before JIT, query plans and the application's " +
             "caches are warm; it is not part of the result. The dashboard report is cached by the application " +
             "(`Reporting:DashboardCacheMinutes`), so its measured calls are cache hits and its first call shows the uncached time.");
        Line();

        Line("## Manifest");
        Line();
        Line("| Item | Value |");
        Line("|---|---|");
        Line($"| Started | {Time(StartedAt)} |");
        Line($"| Finished | {Time(FinishedAt)} ({(FinishedAt - StartedAt).TotalSeconds.ToString("F0", Invariant)} s) |");
        Line($"| Commit | `{Repository.Commit}` |");
        Line($"| Tag | {(Repository.Tag is null ? "none" : $"`{Repository.Tag}`")} |");
        Line($"| Branch | `{Repository.Branch}` |");
        Line($"| Working tree | {(Repository.Dirty ? "**uncommitted changes** (the measured code is not exactly the commit)" : "clean")} |");
        Line($"| API | `{Arguments.BaseUrl}` (client and server on {(Hosts.IsLocal(Arguments.BaseUrl.Host) ? "the same machine" : "different machines")}) |");
        Line($"| Calls per endpoint | {Arguments.Iterations} measured after {Arguments.Warmup} warm-up calls; one at a time, one HTTP connection reused |");
        Line($"| Time of a call | from sending the request to the last byte of the response |");
        Line($"| OS | {Machine.Os} ({Machine.Architecture}) |");
        Line($"| CPU | {Machine.Cpu}, {Machine.LogicalCores} logical cores |");
        Line($"| Memory | {Machine.TotalMemoryGb.ToString("F1", Invariant)} GB total" +
             (Machine.FreeMemoryGb is { } free ? $", {free.ToString("F1", Invariant)} GB free at the start" : "") + " |");
        Line($"| Machine up for | {(int)Machine.Uptime.TotalHours} h {Machine.Uptime.Minutes} min |");
        Line($"| Benchmark runtime | {Machine.Runtime}{(Machine.ServerGc ? ", server GC" : "")} |");

        if (Database is { } db)
        {
            Line($"| Database | {db.Server} |");
            Line($"| SQL Server | {db.Version} |");
            Line($"| Loans | {N(db.Loans)} in total, {N(db.OpenLoans)} open, {N(db.BenchmarkLoans)} added by the benchmark seed |");
            Line($"| Other rows | {N(db.Books)} books, {N(db.Copies)} copies, {N(db.StaffMembers)} staff members, {N(db.Reservations)} reservations, " +
                 $"{N(db.PenaltyRecords)} penalty records, {N(db.Notifications)} notifications |");
        }
        else
        {
            Line("| Database | not read: no connection string; the row counts are unknown |");
        }

        Line();
        Line("## Every measured call, ms");
        Line();
        foreach (var r in Results)
        {
            Line($"<details><summary>{r.Endpoint.Name}</summary>");
            Line();
            Line(string.Join(", ", r.Samples.Select(Ms)));
            Line();
            Line("</details>");
            Line();
        }

        return text.ToString();
    }
}
