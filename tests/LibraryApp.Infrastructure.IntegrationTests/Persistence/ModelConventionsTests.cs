using LibraryApp.Domain.Common;
using LibraryApp.Infrastructure.Persistence;
using LibraryApp.Infrastructure.Persistence.Conventions;
using LibraryApp.Infrastructure.Persistence.Converters;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;

namespace LibraryApp.Infrastructure.IntegrationTests.Persistence;

/// <summary>
/// Part 1 proves the conventions on probe entities (no module has a table yet).
/// Part 2 is a guard over the real model: it starts checking every entity as soon as a group adds one.
/// No database is needed: only the model is built.
/// </summary>
public class ModelConventionsTests
{
    private const string NoDatabase = "Server=unused;Database=unused;Trusted_Connection=True;TrustServerCertificate=True";

    // ---------- Part 1: the conventions on probe entities ----------

    [Fact]
    public void Entity_id_is_generated_by_the_application_even_if_a_configuration_says_otherwise()
    {
        var id = Probe<ProbeParent>().FindPrimaryKey()!.Properties.Single();

        Assert.Equal(ValueGenerated.Never, id.ValueGenerated);
    }

    [Fact]
    public void DateTime_and_nullable_DateTime_get_the_UTC_converter()
    {
        var parent = Probe<ProbeParent>();

        Assert.IsType<UtcDateTimeConverter>(parent.FindProperty(nameof(ProbeParent.CreatedAtUtc))!.GetValueConverter());
        Assert.IsType<UtcDateTimeConverter>(parent.FindProperty(nameof(ProbeParent.ClosedAtUtc))!.GetValueConverter());
    }

    [Fact]
    public void Strings_default_to_256_and_a_configuration_can_override_the_length()
    {
        var parent = Probe<ProbeParent>();

        Assert.Equal(LibraryModelConventions.DefaultStringLength, parent.FindProperty(nameof(ProbeParent.Name))!.GetMaxLength());
        Assert.Equal(32, parent.FindProperty(nameof(ProbeParent.Code))!.GetMaxLength());
        Assert.Equal("nvarchar(max)", parent.FindProperty(nameof(ProbeParent.Description))!.GetColumnType());
    }

    [Fact]
    public void Enums_are_stored_as_int_by_default()
    {
        var status = Probe<ProbeParent>().FindProperty(nameof(ProbeParent.Status))!;

        Assert.Equal("int", status.GetColumnType());
    }

    [Fact]
    public void Relationships_restrict_delete_by_default()
    {
        var foreignKey = Probe<ProbeHistory>().GetForeignKeys().Single();

        Assert.Equal(DeleteBehavior.Restrict, foreignKey.DeleteBehavior);
    }

    [Fact]
    public void An_explicit_cascade_inside_an_aggregate_wins_over_the_convention()
    {
        var foreignKey = Probe<ProbeLine>().GetForeignKeys().Single();

        Assert.Equal(DeleteBehavior.Cascade, foreignKey.DeleteBehavior);
    }

    [Fact]
    public void Owned_types_keep_cascade()
    {
        var ownership = Probe<ProbeParent>().GetNavigations().Single(n => n.Name == nameof(ProbeParent.Notes))
            .TargetEntityType.FindOwnership()!;

        Assert.Equal(DeleteBehavior.Cascade, ownership.DeleteBehavior);
    }

    private static IEntityType Probe<T>()
    {
        using var context = new ProbeContext();
        return context.Model.FindEntityType(typeof(T))!;
    }

    // ---------- Part 2: guard over the real model ----------

    [Fact]
    public void Real_model_every_entity_id_is_generated_by_the_application()
    {
        foreach (var entity in RealEntities().Where(e => typeof(Entity).IsAssignableFrom(e.ClrType)))
        {
            var key = entity.FindPrimaryKey();
            if (key is { Properties.Count: 1 } && key.Properties[0].ClrType == typeof(Guid))
                Assert.True(key.Properties[0].ValueGenerated == ValueGenerated.Never, $"{entity.DisplayName()}.Id may be generated by EF");
        }
    }

    [Fact]
    public void Real_model_every_DateTime_column_is_UTC()
    {
        foreach (var entity in RealEntities())
        foreach (var property in entity.GetProperties().Where(p => p.ClrType == typeof(DateTime) || p.ClrType == typeof(DateTime?)))
            Assert.True(property.GetValueConverter() is UtcDateTimeConverter, $"{entity.DisplayName()}.{property.Name} has no UTC converter");
    }

    [Fact]
    public void Real_model_every_entity_has_a_DbSet()
    {
        // Every table is listed as a DbSet in LibraryDbContext (added by the Integration Owner in the group's pull request).
        var listed = typeof(LibraryDbContext).GetProperties()
            .Where(p => p.PropertyType.IsGenericType && p.PropertyType.GetGenericTypeDefinition() == typeof(DbSet<>))
            .Select(p => p.PropertyType.GetGenericArguments()[0])
            .ToHashSet();

        foreach (var entity in RealEntities().Where(e => !e.IsOwned() && !e.HasSharedClrType))
            Assert.True(listed.Contains(entity.ClrType),
                $"{entity.DisplayName()}: no DbSet<{entity.ClrType.Name}> in LibraryDbContext (Integration Owner adds it with the migration)");
    }

    [Fact]
    public void Real_model_no_table_is_named_after_the_class_in_the_singular()
    {
        // SD-12: plural table names. The name comes from the DbSet property ("Loans"); ToTable(...) in a configuration
        // overrides it. Without either EF would use the class name ("Loan").
        foreach (var entity in RealEntities().Where(e => !e.IsOwned() && !e.HasSharedClrType))
            Assert.True(entity.GetTableName() != entity.ClrType.Name, $"{entity.DisplayName()}: table name must be plural (DbSet name or ToTable)");
    }

    [Fact]
    public void Real_model_no_relationship_cascades_unless_configured_explicitly()
    {
        using var context = new LibraryDbContext(new DbContextOptionsBuilder<LibraryDbContext>().UseSqlServer(NoDatabase).Options);
        var model = (IConventionModel)context.GetService<IDesignTimeModel>().Model;

        foreach (var foreignKey in model.GetEntityTypes().SelectMany(e => e.GetDeclaredForeignKeys())
                     .Where(fk => fk.DeleteBehavior == DeleteBehavior.Cascade && !fk.IsOwnership))
            Assert.True(
                foreignKey.GetDeleteBehaviorConfigurationSource() is ConfigurationSource.Explicit or ConfigurationSource.DataAnnotation,
                $"{foreignKey.DeclaringEntityType.DisplayName()} -> {foreignKey.PrincipalEntityType.DisplayName()}: cascade was not configured explicitly (SD-12: Restrict by default)");
    }

    private static IReadOnlyList<IEntityType> RealEntities()
    {
        using var context = new LibraryDbContext(new DbContextOptionsBuilder<LibraryDbContext>().UseSqlServer(NoDatabase).Options);
        return context.Model.GetEntityTypes().ToList();
    }

    // ---------- probe model ----------

    private enum ProbeStatus { Open = 1, Closed = 2 }

    private sealed class ProbeParent : Entity
    {
        public string Name { get; set; } = "";
        public string Code { get; set; } = "";
        public string Description { get; set; } = "";
        public ProbeStatus Status { get; set; }
        public DateTime CreatedAtUtc { get; set; }
        public DateTime? ClosedAtUtc { get; set; }
        public List<ProbeLine> Lines { get; set; } = [];
        public List<ProbeNote> Notes { get; set; } = [];
    }

    private sealed class ProbeLine : Entity
    {
        public Guid ParentId { get; set; }
    }

    private sealed class ProbeHistory : Entity
    {
        public Guid ParentId { get; set; }
    }

    private sealed class ProbeNote
    {
        public string Text { get; set; } = "";
    }

    private sealed class ProbeContext : DbContext
    {
        protected override void OnConfiguring(DbContextOptionsBuilder options) => options.UseSqlServer(NoDatabase);

        protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder) =>
            LibraryModelConventions.Configure(configurationBuilder);

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<ProbeParent>(b =>
            {
                b.Property(x => x.Id).ValueGeneratedOnAdd();          // a mistake the platform must undo
                b.Property(x => x.Code).HasMaxLength(32);
                b.Property(x => x.Description).HasMaxLength(-1);
                b.HasMany(x => x.Lines).WithOne().HasForeignKey(x => x.ParentId).OnDelete(DeleteBehavior.Cascade);
                b.OwnsMany(x => x.Notes);
            });
            modelBuilder.Entity<ProbeHistory>().HasOne<ProbeParent>().WithMany().HasForeignKey(x => x.ParentId);

            LibraryModelConventions.ApplyApplicationGeneratedIds(modelBuilder);
        }
    }
}
