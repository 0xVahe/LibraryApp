using LibraryApp.Domain.Borrowing;
using LibraryApp.Domain.Catalog;
using LibraryApp.Domain.Staff;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace LibraryApp.Infrastructure.Persistence.Configurations.Borrowing;

/// <summary>
/// Configures the Borrowing Reservation entity.
/// </summary>
public sealed class ReservationConfiguration
    : IEntityTypeConfiguration<Reservation>
{
    /// <summary>
    /// Configures Reservation properties, indexes, and constraints.
    /// </summary>
    public void Configure(EntityTypeBuilder<Reservation> builder)
    {
        // Id is inherited from Entity.
        // It is generated by the application.
        builder.HasKey(reservation => reservation.Id);

        builder.Property(reservation => reservation.Id)
            .ValueGeneratedNever();

        builder.Property(reservation => reservation.BookId)
            .IsRequired();

        builder.Property(reservation => reservation.StaffMemberId)
            .IsRequired();

        builder.Property(reservation => reservation.CreatedAtUtc)
            .IsRequired();

        builder.Property(reservation => reservation.ReadyUntilAtUtc)
            .IsRequired(false);

        // ReservationStatus is stored as an integer.
        builder.Property(reservation => reservation.Status)
            .IsRequired();

        builder.Property(reservation => reservation.QueuePosition)
            .IsRequired();

        // SQL Server manages the concurrency token.
        builder.Property(reservation => reservation.RowVersion)
            .IsRowVersion()
            .IsConcurrencyToken();

        builder.HasOne<Book>()
            .WithMany()
            .HasForeignKey(reservation => reservation.BookId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.HasOne<StaffMember>()
            .WithMany()
            .HasForeignKey(reservation => reservation.StaffMemberId)
            .OnDelete(DeleteBehavior.Restrict);

        // Supports FIFO queue queries for one book.
        builder.HasIndex(reservation => new
        {
            reservation.BookId,
            reservation.Status,
            reservation.CreatedAtUtc
        })
        .HasDatabaseName(
            "IX_Reservations_BookId_Status_CreatedAtUtc");

        // Helps count active reservations for one member.
        builder.HasIndex(reservation => new
        {
            reservation.StaffMemberId,
            reservation.Status
        })
        .HasDatabaseName(
            "IX_Reservations_StaffMemberId_Status");

        /*
         * Only one active reservation is allowed for one member and one book.
         *
         * Waiting        = 1
         * ReadyForPickup = 2
         */
        builder.HasIndex(reservation => new
        {
            reservation.StaffMemberId,
            reservation.BookId
        })
        .IsUnique()
        .HasFilter("[Status] IN (1, 2)")
        .HasDatabaseName(
            "UX_Reservations_Active_StaffMemberId_BookId");

        builder.ToTable(table =>
        {
            /*
             * QueuePosition convention:
             *
             * Waiting:    1, 2, 3, ...
             * Other state: 0
             *
             * ReservationStatus.Waiting = 1
             */
            table.HasCheckConstraint(
                "CK_Reservations_QueuePosition",
                """
                ([Status] = 1 AND [QueuePosition] >= 1)
                OR
                ([Status] <> 1 AND [QueuePosition] = 0)
                """);
        });
    }
}