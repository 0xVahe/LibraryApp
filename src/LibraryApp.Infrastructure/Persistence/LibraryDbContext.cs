using LibraryApp.Infrastructure.Identity;
using LibraryApp.Infrastructure.Jobs;
using LibraryApp.Infrastructure.Messaging;
using LibraryApp.Infrastructure.Persistence.Conventions;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using LibraryApp.Domain.Catalog;
using LibraryApp.Domain.Staff;
using LibraryApp.Domain.Borrowing;
using LibraryApp.Domain.Notifications;
    
namespace LibraryApp.Infrastructure.Persistence;

/// <summary>
/// The single DbContext of the single shared database. Owned by the Integration Owner; groups do not edit this file.
/// <para>
/// Identity tables (AspNet*) live here too (X-09); their DbSets come from <see cref="IdentityDbContext{TUser,TRole,TKey}"/>.
/// </para>
/// <para>
/// One <c>DbSet</c> per entity, grouped by module. A group adds its entity (Domain) and its
/// <c>IEntityTypeConfiguration&lt;T&gt;</c> (<c>Persistence/Configurations/&lt;Module&gt;/</c>, picked up automatically)
/// and labels the pull request <c>needs-migration</c>; the Integration Owner adds the <c>DbSet</c> here and the
/// migration as commits in that pull request. The property name is the table name (SD-12: plural).
/// </para>
/// <para>
/// Rules for every table live in <see cref="LibraryModelConventions"/>; a configuration overrides a default explicitly
/// (<c>HasMaxLength</c>, <c>OnDelete</c>, <c>HasConversion</c>) and never repeats it.
/// </para>
/// </summary>
public sealed class LibraryDbContext(DbContextOptions<LibraryDbContext> options)
    : IdentityDbContext<AppUser, IdentityRole<Guid>, Guid>(options)
{
    // Catalog (Group 1)
    
    public DbSet<Publisher> Publishers => Set<Publisher>();
    public DbSet<Category> Categories => Set<Category>();
    public DbSet<Author> Authors => Set<Author>();
    public DbSet<Book> Books => Set<Book>();
    public DbSet<BookAuthor> BookAuthors => Set<BookAuthor>();
    public DbSet<BookCopy> BookCopies => Set<BookCopy>();
    public DbSet<BookSuggestion> BookSuggestions => Set<BookSuggestion>();

    // Staff (Group 2)
    
    public DbSet<Department> Departments => Set<Department>();
    public DbSet<StaffMember> StaffMembers => Set<StaffMember>();
    public DbSet<StaffCategory> StaffCategories => Set<StaffCategory>();

    // Borrowing (Group 3)
    
    public DbSet<Loan> Loans => Set<Loan>();
    public DbSet<Reservation> Reservations => Set<Reservation>();
    public DbSet<PenaltyRecord> PenaltyRecords => Set<PenaltyRecord>();

    // Notifications (Group 4)

    public DbSet<Notification> Notifications => Set<Notification>();
    public DbSet<NotificationTemplate> NotificationTemplates => Set<NotificationTemplate>();

    // Platform (Integration Owner)

    public DbSet<OutboxMessage> OutboxMessages => Set<OutboxMessage>();
    public DbSet<ProcessedEvent> ProcessedEvents => Set<ProcessedEvent>();
    public DbSet<JobRun> JobRuns => Set<JobRun>();   // daily job runs (SD-10)

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder) =>
        LibraryModelConventions.Configure(configurationBuilder);

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // First: Identity maps its tables; our configurations below may override it.
        base.OnModelCreating(modelBuilder);

        modelBuilder.ApplyConfigurationsFromAssembly(typeof(LibraryDbContext).Assembly);

        // After the configurations: the rule must win over anything a configuration says about entity ids.
        LibraryModelConventions.ApplyApplicationGeneratedIds(modelBuilder);

        // After the configurations: Restrict wherever EF Core itself chose cascade (SD-12).
        LibraryModelConventions.ApplyRestrictDeleteDefault(modelBuilder);
    }
}
